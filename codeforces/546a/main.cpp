using namespace std;

void solve() {
    int k, n, w, cost = 0;
    cin >> k >> n >> w;
    for(int i = 1; i <= w; ++i) cost += (i * k);
    cout << (cost > n ? cost - n : 0) << "\n";
}

int main() {
    ios_base::sync_with_stdio(0);
    cin.tie(0);
    cout.tie(0);
    int tc = 1;
    for (int t = 1; t <= tc; t++) {
        solve();
    }
}
